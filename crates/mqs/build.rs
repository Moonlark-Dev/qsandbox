//! Build script: embed the built GUI (`web/dist`) into the binary when present.
//!
//! Mirrors the behaviour the Python build hook had: a source checkout without a
//! frontend build still compiles and serves the "frontend not built" page, while
//! release builds embed the real GUI so a single `mqs` binary is self-contained.

use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist = manifest.join("../../web/dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-changed=src/schema.sql");

    let mut entries = Vec::new();
    if dist.join("index.html").exists() {
        collect(&dist, &dist, &mut entries);
    }
    entries.sort();

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("web_assets.rs");
    let mut code = String::from("// generated by build.rs\n");
    code.push_str("pub static WEB_ASSETS: &[(&str, &[u8], &str)] = &[\n");
    for (rel, abs) in &entries {
        let mime = mime_for(rel);
        code.push_str(&format!(
            "    ({:?}, include_bytes!({:?}), {:?}),\n",
            rel,
            abs.to_string_lossy(),
            mime
        ));
    }
    code.push_str("];\n");
    fs::write(out, code).unwrap();
}

fn collect(root: &PathBuf, dir: &PathBuf, out: &mut Vec<(String, PathBuf)>) {
    let Ok(read) = fs::read_dir(dir) else { return };
    for entry in read.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(rel) = path.strip_prefix(root) {
            out.push((rel.to_string_lossy().replace('\\', "/"), path.clone()));
        }
    }
}

fn mime_for(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or("") {
        "html" => "text/html; charset=utf-8",
        "js" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "map" => "application/json",
        _ => "application/octet-stream",
    }
}
